#!/usr/bin/env python3
"""Cross-fitted residual-correlation and alignment diagnostics.

The residual matrix is a diagnostic proxy.  It is generated by group-held-out
ridge VAR predictions, so no recording row contributes both fitting and residuals
within an outer fold.  It is not asserted to identify the theorem's structural
innovation covariance under arbitrary model misspecification.
"""

from __future__ import annotations

import argparse
import json
from pathlib import Path
from typing import List, Sequence, Tuple

import numpy as np
import pandas as pd
from scipy.stats import spearmanr
from sklearn.linear_model import Ridge
from sklearn.model_selection import KFold

from experiments.common import (DEFAULT_DATASET, DEFAULT_SBTG, load_dataset, load_monoamine_networks,
                    load_reference_networks, load_sbtg, partial_rank_correlation,
                    reorder_square, safe_auroc, safe_spearman)


def parse_args() -> argparse.Namespace:
    parser = argparse.ArgumentParser()
    parser.add_argument("--dataset-dir", type=Path, default=DEFAULT_DATASET)
    parser.add_argument("--sbtg-file", type=Path, default=DEFAULT_SBTG)
    parser.add_argument("--out-dir", type=Path, required=True)
    parser.add_argument("--var-order", type=int, default=20)
    parser.add_argument("--outer-folds", type=int, default=5)
    parser.add_argument("--inner-folds", type=int, default=4)
    parser.add_argument("--ridge-alphas", type=float, nargs="+", default=[0.01, 0.1, 1.0, 10.0, 100.0])
    parser.add_argument("--permutations", type=int, default=2000)
    parser.add_argument("--seed", type=int, default=2026)
    parser.add_argument("--max-recordings", type=int)
    parser.add_argument("--max-frames", type=int)
    return parser.parse_args()


def make_var_rows(traces: Sequence[np.ndarray], order: int) -> Tuple[np.ndarray, np.ndarray, np.ndarray]:
    features, outcomes, groups = [], [], []
    for group, trace in enumerate(traces):
        clean = np.nan_to_num(np.asarray(trace, dtype=float), nan=0.0, posinf=0.0, neginf=0.0)
        if len(clean) <= order:
            continue
        for t in range(order, len(clean)):
            features.append(np.concatenate([clean[t - lag] for lag in range(1, order + 1)]))
            outcomes.append(clean[t])
            groups.append(group)
    return np.asarray(features), np.asarray(outcomes), np.asarray(groups)


def grouped_folds(n_groups: int, n_splits: int, seed: int) -> List[Tuple[np.ndarray, np.ndarray]]:
    if n_groups < 2:
        raise ValueError("At least two composite recording rows are required")
    splitter = KFold(n_splits=min(n_splits, n_groups), shuffle=True, random_state=seed)
    labels = np.arange(n_groups)
    return [(labels[train], labels[test]) for train, test in splitter.split(labels)]


def choose_alpha(X: np.ndarray, y: np.ndarray, groups: np.ndarray, train_groups: np.ndarray,
                 alphas: Sequence[float], n_splits: int, seed: int) -> Tuple[float, pd.DataFrame]:
    if len(alphas) == 1:
        return float(alphas[0]), pd.DataFrame([
            {"alpha": float(alphas[0]), "mean_validation_mse": np.nan,
             "selection": "fixed a priori; no inner fitting"}
        ])
    fold_rows = []
    local = grouped_folds(len(train_groups), n_splits, seed)
    for alpha in alphas:
        losses = []
        for inner_train_pos, inner_val_pos in local:
            inner_train = train_groups[inner_train_pos]
            inner_val = train_groups[inner_val_pos]
            train_mask, val_mask = np.isin(groups, inner_train), np.isin(groups, inner_val)
            x_mean, x_std = X[train_mask].mean(0), X[train_mask].std(0) + 1e-8
            y_mean, y_std = y[train_mask].mean(0), y[train_mask].std(0) + 1e-8
            model = Ridge(alpha=alpha, fit_intercept=True, solver="cholesky")
            model.fit((X[train_mask] - x_mean) / x_std, (y[train_mask] - y_mean) / y_std)
            pred = model.predict((X[val_mask] - x_mean) / x_std) * y_std + y_mean
            losses.append(float(np.mean((y[val_mask] - pred) ** 2)))
        fold_rows.append({"alpha": alpha, "mean_validation_mse": np.mean(losses)})
    table = pd.DataFrame(fold_rows)
    return float(table.loc[table["mean_validation_mse"].idxmin(), "alpha"]), table


def cross_fitted_residuals(X: np.ndarray, y: np.ndarray, groups: np.ndarray, n_groups: int,
                           outer_folds: int, inner_folds: int, alphas: Sequence[float], seed: int):
    residual = np.full_like(y, np.nan, dtype=float)
    fold_rows, tuning_rows = [], []
    for fold, (train_groups, test_groups) in enumerate(grouped_folds(n_groups, outer_folds, seed)):
        alpha, tuning = choose_alpha(X, y, groups, train_groups, alphas, inner_folds, seed + fold + 1)
        tuning.insert(0, "outer_fold", fold)
        tuning_rows.append(tuning)
        train_mask, test_mask = np.isin(groups, train_groups), np.isin(groups, test_groups)
        x_mean, x_std = X[train_mask].mean(0), X[train_mask].std(0) + 1e-8
        y_mean, y_std = y[train_mask].mean(0), y[train_mask].std(0) + 1e-8
        model = Ridge(alpha=alpha, fit_intercept=True, solver="cholesky")
        model.fit((X[train_mask] - x_mean) / x_std, (y[train_mask] - y_mean) / y_std)
        pred = model.predict((X[test_mask] - x_mean) / x_std) * y_std + y_mean
        residual[test_mask] = y[test_mask] - pred
        baseline = np.broadcast_to(y_mean, y[test_mask].shape)
        fold_rows.append({
            "outer_fold": fold, "alpha": alpha, "n_train_rows": int(train_mask.sum()),
            "n_test_rows": int(test_mask.sum()), "n_train_recordings": len(train_groups),
            "n_test_recordings": len(test_groups), "mse": float(np.mean((y[test_mask] - pred) ** 2)),
            "constant_mean_mse": float(np.mean((y[test_mask] - baseline) ** 2)),
            "heldout_recording_indices": ",".join(map(str, test_groups)),
        })
    if np.isnan(residual).any():
        raise RuntimeError("Some outcome rows did not receive held-out predictions")
    return residual, pd.DataFrame(fold_rows), pd.concat(tuning_rows, ignore_index=True)


def qap_pvalue(x_matrix: np.ndarray, y_matrix: np.ndarray, mask: np.ndarray, observed: float,
               permutations: int, rng: np.random.Generator, partial_control: np.ndarray | None = None) -> float:
    exceed = 0
    n = len(x_matrix)
    for _ in range(permutations):
        perm = rng.permutation(n)
        permuted = y_matrix[np.ix_(perm, perm)]
        permuted_mask = mask[np.ix_(perm, perm)]
        if partial_control is None:
            value = safe_spearman(x_matrix[permuted_mask], permuted[permuted_mask])
        else:
            value = partial_rank_correlation(
                x_matrix[permuted_mask], permuted[permuted_mask], partial_control[permuted_mask]
            )
        exceed += int(np.isfinite(value) and abs(value) >= abs(observed))
    return (exceed + 1) / (permutations + 1)


def main() -> None:
    args = parse_args()
    args.out_dir.mkdir(parents=True, exist_ok=True)
    traces, names, row_meta = load_dataset(args.dataset_dir)
    if args.max_recordings:
        traces, row_meta = traces[:args.max_recordings], row_meta.iloc[:args.max_recordings].copy()
    if args.max_frames:
        traces = [trace[:args.max_frames] for trace in traces]
    X, y, groups = make_var_rows(traces, args.var_order)
    residual, folds, tuning = cross_fitted_residuals(
        X, y, groups, len(traces), args.outer_folds, args.inner_folds, args.ridge_alphas, args.seed
    )
    corr = np.corrcoef(residual, rowvar=False)
    abs_corr = np.abs(corr)
    offdiag = ~np.eye(len(names), dtype=bool)
    summary = {
        "estimand": "correlation of group-held-out ridge-VAR residuals (diagnostic proxy, not structural Omega)",
        "data_unit": "composite recording row produced by the head/tail preparation pipeline",
        "n_composite_rows": len(traces), "n_neurons": len(names), "n_residual_timepoints": len(residual),
        "var_order": args.var_order, "outer_folds": min(args.outer_folds, len(traces)),
        "ridge_alphas_requested": list(args.ridge_alphas),
        "qap_permutations": args.permutations,
        "mean_abs_offdiagonal_correlation": float(abs_corr[offdiag].mean()),
        "median_abs_offdiagonal_correlation": float(np.median(abs_corr[offdiag])),
        "p90_abs_offdiagonal_correlation": float(np.quantile(abs_corr[offdiag], 0.90)),
        "limitations": ["VAR misspecification can remain in residuals", "calcium preprocessing can induce correlation",
                        "donor-based missing-neuron imputation can induce shared trajectories",
                        "the source data construction does not establish that each paired row is one biological worm"],
    }
    folds.to_csv(args.out_dir / "residual_outer_fold_prediction.csv", index=False)
    tuning.to_csv(args.out_dir / "residual_inner_alpha_tuning.csv", index=False)
    row_meta.to_csv(args.out_dir / "residual_composite_row_manifest.csv", index=False)
    np.savez(args.out_dir / "residual_crossfit_residual_correlation.npz", corr=corr, abs_corr=abs_corr,
             neuron_names=np.asarray(names), residuals=residual, residual_group=groups)

    sbtg_mu, sbtg_sig, sbtg_names = load_sbtg(args.sbtg_file)
    if sbtg_names != names:
        sbtg_mu = {lag: reorder_square(matrix, sbtg_names, names)[0] for lag, matrix in sbtg_mu.items()}
        sbtg_sig = {lag: reorder_square(matrix, sbtg_names, names)[0].astype(bool) for lag, matrix in sbtg_sig.items()}
    references = load_reference_networks(names)
    for network, labels in load_monoamine_networks(names).items():
        references[network] = (labels, offdiag)
    rng = np.random.default_rng(args.seed)
    alignment_rows = []
    for ref_name, (labels, mask) in references.items():
        residual_assoc = safe_spearman(abs_corr[mask], labels[mask].astype(float))
        alignment_rows.append({
            "comparison": "residual_reference", "reference": ref_name, "lag": np.nan,
            "spearman": residual_assoc, "partial_spearman": np.nan,
            "qap_p_two_sided": qap_pvalue(abs_corr, labels.astype(float), mask, residual_assoc,
                                            args.permutations, rng),
            "auroc": safe_auroc(labels[mask], abs_corr[mask]), "n_pairs": int(mask.sum()),
        })
        for lag, mu in sbtg_mu.items():
            score = np.abs(mu)
            rho = safe_spearman(score[mask], labels[mask].astype(float))
            partial = partial_rank_correlation(score[mask], labels[mask].astype(float), abs_corr[mask])
            alignment_rows.append({
                "comparison": "sbtg_reference", "reference": ref_name, "lag": lag,
                "spearman": rho, "partial_spearman": partial,
                "qap_p_two_sided": qap_pvalue(score, labels.astype(float), mask, rho,
                                                args.permutations, rng),
                "partial_qap_p_two_sided": qap_pvalue(score, labels.astype(float), mask, partial,
                                                        args.permutations, rng, abs_corr),
                "auroc": safe_auroc(labels[mask], score[mask]), "n_pairs": int(mask.sum()),
            })
    for lag, mu in sbtg_mu.items():
        alignment_rows.append({
            "comparison": "sbtg_residual", "reference": "residual_proxy", "lag": lag,
            "spearman": safe_spearman(np.abs(mu)[offdiag], abs_corr[offdiag]),
            "partial_spearman": np.nan, "qap_p_two_sided": np.nan,
            "auroc": np.nan, "n_pairs": int(offdiag.sum()),
        })
    pd.DataFrame(alignment_rows).to_csv(args.out_dir / "residual_alignment_tests.csv", index=False)

    robustness = []
    for ref_name, (labels, mask) in references.items():
        for lag, mu in sbtg_mu.items():
            score = np.abs(mu)
            for excluded_fraction in (0.0, 0.10, 0.25):
                kept = mask.copy()
                if excluded_fraction:
                    threshold = np.quantile(abs_corr[mask], 1 - excluded_fraction)
                    kept &= abs_corr < threshold
                robustness.append({
                    "reference": ref_name, "lag": lag, "excluded_top_residual_fraction": excluded_fraction,
                    "n_pairs": int(kept.sum()), "n_positive": int(labels[kept].sum()),
                    "auroc": safe_auroc(labels[kept], score[kept]),
                    "significant_edges": int(sbtg_sig.get(lag, np.zeros_like(mask))[kept].sum()),
                })
    pd.DataFrame(robustness).to_csv(args.out_dir / "residual_auroc_residual_exclusion.csv", index=False)

    quantile_rows = []
    pair_values = abs_corr[offdiag]
    quantile_edges = np.quantile(pair_values, np.linspace(0, 1, 5))
    for lag, sig in sbtg_sig.items():
        for quartile in range(4):
            lower, upper = quantile_edges[quartile], quantile_edges[quartile + 1]
            pair_mask = offdiag & (abs_corr >= lower)
            pair_mask &= (abs_corr <= upper) if quartile == 3 else (abs_corr < upper)
            quantile_rows.append({
                "lag": lag, "residual_abs_corr_quartile": quartile + 1,
                "lower": lower, "upper": upper, "n_pairs": int(pair_mask.sum()),
                "significant_edges": int(sig[pair_mask].sum()),
                "significant_edge_rate": float(sig[pair_mask].mean()),
            })
    pd.DataFrame(quantile_rows).to_csv(args.out_dir / "residual_significance_by_residual_quartile.csv", index=False)
    with (args.out_dir / "residual_summary.json").open("w") as handle:
        json.dump(summary, handle, indent=2)
    print(json.dumps(summary, indent=2))


if __name__ == "__main__":
    main()
